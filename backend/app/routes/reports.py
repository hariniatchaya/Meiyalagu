from pathlib import Path
from uuid import uuid4
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

from app.database import get_db
from app.models import User, SkinAnalysis, Report
from app.routes.auth_routes import get_current_user
from app.config import REPORTS_DIR

router = APIRouter(prefix="/api/reports", tags=["Reports"])


def generate_pdf_report(analysis: SkinAnalysis, user: User) -> Path:
    """Generate professional PDF clinical summary report."""
    filename = f"Meiyalagu_{analysis.record_id}.pdf"
    path = REPORTS_DIR / filename

    doc = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontSize=20,
        textColor=colors.HexColor("#7049df"),
        spaceAfter=6
    )
    section_style = ParagraphStyle(
        "Section",
        parent=styles["Heading2"],
        fontSize=14,
        textColor=colors.HexColor("#1e1b4b"),
        spaceBefore=12,
        spaceAfter=6
    )

    content = [
        Paragraph("Meiyalagu AI - Skin Assessment Summary", title_style),
        Paragraph("Preliminary AI Image Analysis Report", styles["Normal"]),
        HRFlowable(width="100%", thickness=1, color=colors.HexColor("#e2e8f0"), spaceBefore=10, spaceAfter=15),
        Paragraph(f"<b>Patient / User:</b> {user.name} ({user.email})", styles["Normal"]),
        Paragraph(f"<b>Record ID:</b> {analysis.record_id}", styles["Normal"]),
        Paragraph(f"<b>Date:</b> {analysis.created_at.strftime('%Y-%m-%d %H:%M UTC') if analysis.created_at else 'Recent'}", styles["Normal"]),
        Spacer(1, 12),
        Paragraph("Classification Results", section_style),
        Paragraph(f"<b>Predicted Condition:</b> {analysis.predicted_class or 'Pending'}", styles["Normal"]),
        Paragraph(f"<b>Model Confidence:</b> {f'{analysis.confidence:.1%}' if analysis.confidence else 'N/A'}", styles["Normal"]),
        Paragraph(f"<b>Assessed Risk Level:</b> {analysis.risk_level or 'Informational'}", styles["Normal"]),
        Spacer(1, 15),
        HRFlowable(width="100%", thickness=1, color=colors.HexColor("#f87171"), spaceBefore=10, spaceAfter=10),
        Paragraph(
            "<b>Clinical Disclaimer:</b> This report is generated by Meiyalagu AI for informational and preliminary "
            "screening purposes only. It is NOT a clinical diagnosis. Please consult a qualified dermatologist "
            "or healthcare practitioner for clinical evaluation.",
            styles["Italic"]
        )
    ]

    doc.build(content)
    return path


@router.post("/generate/{analysis_id}")
def create_report(
    analysis_id: int,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    analysis = db.query(SkinAnalysis).filter(
        SkinAnalysis.id == analysis_id,
        SkinAnalysis.user_id == user.id
    ).first()

    if not analysis:
        raise HTTPException(status_code=404, detail="Analysis record not found")

    pdf_file = generate_pdf_report(analysis, user)
    report = Report(
        report_id=f"REP-{uuid4().int % 1000000:06d}",
        user_id=user.id,
        analysis_id=analysis.id,
        pdf_path=str(pdf_file)
    )
    db.add(report)
    db.commit()

    return {
        "report_id": report.report_id,
        "filename": pdf_file.name,
        "download_url": f"/api/reports/download/{analysis_id}"
    }


@router.get("/download/{analysis_id}")
def download_report(
    analysis_id: int,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    analysis = db.query(SkinAnalysis).filter(
        SkinAnalysis.id == analysis_id,
        SkinAnalysis.user_id == user.id
    ).first()

    if not analysis:
        raise HTTPException(status_code=404, detail="Analysis record not found")

    pdf_file = REPORTS_DIR / f"Meiyalagu_{analysis.record_id}.pdf"
    if not pdf_file.exists():
        pdf_file = generate_pdf_report(analysis, user)

    return FileResponse(
        str(pdf_file),
        media_type="application/pdf",
        filename=f"Meiyalagu_{analysis.record_id}.pdf"
    )
